"""Machine-readable catalog for bounded Citry UI quality scenarios."""

from __future__ import annotations

import json
import sys
from dataclasses import asdict, dataclass
from enum import Enum


# `enum.StrEnum` is Python 3.11 and later, and this package supports 3.10, so the
# mixin spelling stands in for it. The one difference is that `str()` on a member
# gives `ScenarioStatus.READY` rather than `ready`; these values are compared and
# serialized through `.value`, never interpolated, so it does not reach output.
class StrEnum(str, Enum):
    """A string-valued enum that compares equal to its plain string value."""


class ScenarioStatus(StrEnum):
    """Whether tools may currently count a scenario as executable evidence."""

    READY = "ready"
    PLANNED = "planned"


class QualityTool(StrEnum):
    """A Phase 7.5 consumer of rendered scenarios."""

    AXE = "axe"
    BROWSER = "browser"
    CSS = "css-coexistence"
    DOCS = "docs"
    HTML = "nu-html"
    LIGHTHOUSE = "lighthouse"
    PERFORMANCE = "performance"
    SCREENSHOT = "screenshot"


@dataclass(frozen=True, slots=True)
class Scenario:
    """One stable scenario and the public states it deliberately exercises."""

    id: str
    family: str
    purpose: str
    states: tuple[str, ...]
    profiles: tuple[str, ...]
    tools: tuple[QualityTool, ...]
    expected_components: tuple[str, ...]
    expected_assets: tuple[str, ...]
    fixture: str
    action_states: tuple[str, ...]
    ready_selector: str
    standalone: bool
    status: ScenarioStatus

    def manifest_value(self) -> dict[str, object]:
        value = asdict(self)
        value["status"] = self.status.value
        value["tools"] = [tool.value for tool in self.tools]
        return value


