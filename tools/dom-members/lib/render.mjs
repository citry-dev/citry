// Writes the classified table as a Rust module of sorted constant arrays.

const ANSWER = {
  WritesText: "DomAnswer::WritesText",
  ReflectBoolean: "DomAnswer::ReflectBoolean",
  Unknown: "DomAnswer::Unknown",
};

export function renderRust(table, versions) {
  const lines = [];
  lines.push("// @generated by tools/dom-members/generate.mjs. Do not edit by hand:");
  lines.push("// run `pnpm --dir tools/dom-members run generate` instead.");
  lines.push("//");
  lines.push("// For each HTML element and lowercase attribute name, what Vue's first");
  lines.push("// client render leaves in the attribute, in every browser from the floor");
  lines.push("// versions listed below onward. A name missing from an element's list and");
  lines.push("// from `BASE` is `WritesText`. See tools/dom-members/lib/classify.mjs for");
  lines.push("// the rules.");
  lines.push("//");
  lines.push("// Inputs:");
  for (const [name, version] of Object.entries(versions)) {
    lines.push(`// - ${name} ${version}`);
  }
  lines.push("//");
  lines.push(
    `// Floor: ${Object.entries(table.floor)
      .map(([browser, version]) => `${browser} ${version}`)
      .join(", ")}`,
  );
  lines.push("");
  lines.push("use crate::server_render::DomAnswer;");
  lines.push("");
  lines.push("/// Tags whose members no table can know, so every name is `Unknown`.");
  lines.push(`pub(crate) const ALL_UNKNOWN_TAGS: &[&str] = &[${table.allUnknownTags.map(quote).join(", ")}];`);
  lines.push("");
  lines.push("/// Answers for an element no element list names (`HTMLUnknownElement`),");
  lines.push("/// which every element starts from. Sorted by name.");
  lines.push("#[rustfmt::skip]");
  lines.push("pub(crate) const BASE: &[(&str, DomAnswer)] = &[");
  for (const [name, answer] of Object.entries(table.base)) {
    lines.push(`    (${quote(name)}, ${ANSWER[answer]}),`);
  }
  lines.push("];");
  lines.push("");
  lines.push("/// Each element's answers that differ from `BASE`. Sorted by tag, then name.");
  lines.push("#[rustfmt::skip]");
  lines.push("pub(crate) const ELEMENTS: &[(&str, &[(&str, DomAnswer)])] = &[");
  for (const [tag, answers] of Object.entries(table.elements)) {
    const entries = Object.entries(answers);
    if (entries.length === 0) {
      lines.push(`    (${quote(tag)}, &[]),`);
      continue;
    }
    lines.push(`    (${quote(tag)}, &[`);
    for (const [name, answer] of entries) {
      lines.push(`        (${quote(name)}, ${ANSWER[answer]}),`);
    }
    lines.push("    ]),");
  }
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

function quote(text) {
  if (!/^[a-z0-9-]+$/.test(text)) {
    throw new Error(`unexpected name ${JSON.stringify(text)} in the table`);
  }
  return `"${text}"`;
}
