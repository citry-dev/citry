"""
Pin the build backends that uv downloads to build Citry's packages, with hashes.

Each package under `packages/py/` names its build backend in `[build-system]
requires` (setuptools, or maturin for citry-core). When uv builds or syncs a
package, it downloads that backend from PyPI into a temporary build
environment. `uv.lock` does not cover those downloads, so the root
`pyproject.toml` lists every backend in `[tool.uv] build-constraint-dependencies`
with an exact version and its sha256 hashes, and sets `require-build-hashes` so
uv refuses any build download it cannot check. It also pins the backends in
`THIRD_PARTY_BUILD_REQUIREMENTS`, which a few locked third-party packages need
where they ship no wheel.

The list sits between two marker comments and is generated by this script:

    python scripts/build_constraints.py update   # refresh pins and hashes
    uv lock                                      # record them in uv.lock

A standalone project under the repository root that is not a workspace member
(the benchmark runners, which build with hatchling) gets no pins from the root:
uv reads `require-build-hashes` from the nearest `[tool.uv]` table, but reads the
pins, and the copy of them recorded in `uv.lock`, from the project's own
workspace root, which is the project itself. Each such project therefore carries
its own `[tool.uv]` table with the same settings and a generated block of its own,
and `update` rewrites every block. Run `uv lock` in each of these projects too.

Some builders pass `--no-config` (the distribution verifiers rebuild a wheel
from a freshly built sdist that way), so they never see the root table. They call
`export` to write the same pins as a requirements file and pass it to uv with
`constraint_args`.

This module uses only the standard library, because the distribution
verifiers run it in a Python that has no other packages installed.
"""

from __future__ import annotations

import argparse
import contextlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final, NamedTuple

import tomllib

if TYPE_CHECKING:
    from collections.abc import Iterator, Sequence

REPO_ROOT: Final = Path(__file__).resolve().parents[1]
ROOT_PYPROJECT: Final = REPO_ROOT / "pyproject.toml"
WORKSPACE_PROJECT_PATTERN: Final = "packages/py/*/pyproject.toml"
# Standalone uv projects: not workspace members, but with a build backend of their own.
STANDALONE_PROJECT_PATTERNS: Final = ("benchmarks/*/runner/pyproject.toml",)
BEGIN_MARKER: Final = "# BEGIN build constraints, generated by `python scripts/build_constraints.py update`"
END_MARKER: Final = "# END build constraints"
# Build environments run on the oldest supported Python too, so resolve from
# there across every platform.
OLDEST_PYTHON: Final = "3.11"
# A few locked third-party packages publish no wheel for some supported
# interpreter, so uv builds them from their sdist, and require-build-hashes
# refuses that build unless its backend is pinned here too. PyYAML has no wheel
# for CPython 3.15 or PyPy 3.11 and builds with Cython, and Brotli has none for
# free-threaded CPython 3.14 and builds with pkgconfig (setuptools, their other
# backend, is already pinned for the workspace packages).
THIRD_PARTY_BUILD_REQUIREMENTS: Final = ("Cython>=3.0", "pkgconfig")

# Hatchling asks for `editables` only while building an editable install, which
# is how `uv sync` installs a project, so it is missing from the backend's own
# `requires` list and `uv pip compile` never sees it. Without a pin, the sync
# stops with "no trusted hash was provided for: `editables`".
BACKEND_EXTRA_REQUIREMENTS: Final = {"hatchling": ("editables~=0.3",)}

_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")
_ENTRY = re.compile(r'\{\s*requirement\s*=\s*"(?P<requirement>[^"]+)"\s*,\s*hashes\s*=\s*\[(?P<hashes>[^\]]*)\]\s*\}')
_HASH = re.compile(r'"(?P<hash>sha256:[0-9a-f]{64})"')


class BuildConstraintError(RuntimeError):
    """The generated build-constraint block is missing or malformed."""


class Pin(NamedTuple):
    """One build dependency: an exact requirement and the hashes uv accepts for it."""

    requirement: str
    hashes: tuple[str, ...]


def _load_toml(text: str) -> dict[str, Any]:
    loaded: dict[str, Any] = tomllib.loads(text)
    return loaded


def marked_block(text: str) -> tuple[int, int]:
    """Return the start and end offsets of the generated lines between the markers."""
    begin = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    # One block keeps `update` from rewriting the wrong list.
    if begin < 0 or end < 0 or end < begin or text.count(BEGIN_MARKER) != 1 or text.count(END_MARKER) != 1:
        raise BuildConstraintError(
            f"{ROOT_PYPROJECT.name} needs exactly one {BEGIN_MARKER!r} ... {END_MARKER!r} block "
            "inside [tool.uv] build-constraint-dependencies"
        )
    start = text.index("\n", begin) + 1
    # The end offset stops at the start of the END marker's line, keeping its indent.
    stop = text.rindex("\n", 0, end) + 1
    return start, stop


def parse_pins(text: str) -> list[Pin]:
    """Read the pins from the generated block of the root pyproject text."""
    start, stop = marked_block(text)
    block = text[start:stop]
    pins = [
        Pin(match.group("requirement"), tuple(h.group("hash") for h in _HASH.finditer(match.group("hashes"))))
        for match in _ENTRY.finditer(block)
    ]
    # A block that has lines but no parsable entry means the format drifted
    # from what `render_block` writes, and exporting nothing would silently
    # turn the hash check off for --no-config builds.
    if block.strip() and not pins:
        raise BuildConstraintError(
            "the generated build-constraint block has no readable entries; "
            "run python scripts/build_constraints.py update"
        )
    return pins


def render_block(pins: Sequence[Pin], *, indent: str = "    ") -> str:
    """Render pins as the TOML inline tables that sit between the markers."""
    lines: list[str] = []
    for pin in pins:
        lines.append(f'{indent}{{ requirement = "{pin.requirement}", hashes = [')
        lines.extend(f'{indent}    "{digest}",' for digest in pin.hashes)
        lines.append(f"{indent}] }},")
    return "".join(f"{line}\n" for line in lines)


def workspace_project_files(root: Path = REPO_ROOT) -> list[Path]:
    """Return the pyproject.toml of every workspace package."""
    return sorted(root.glob(WORKSPACE_PROJECT_PATTERN))


def standalone_project_files(root: Path = REPO_ROOT) -> list[Path]:
    """Return the pyproject.toml of every standalone project that carries its own pins."""
    return [path for pattern in STANDALONE_PROJECT_PATTERNS for path in sorted(root.glob(pattern))]


def project_requirements(pyproject: Path) -> list[str]:
    """Return the build requirements of one project: its `[build-system] requires` plus the backend extras."""
    build_system = _load_toml(pyproject.read_text(encoding="utf-8")).get("build-system", {})
    requirements = list(build_system.get("requires", []))
    for requirement in list(requirements):
        # This module may not import `packaging`, so read the project name with a pattern.
        name = _NAME.match(requirement)
        if name:
            requirements.extend(BACKEND_EXTRA_REQUIREMENTS.get(re.sub(r"[-_.]+", "-", name.group()).lower(), ()))
    return requirements


def build_requirements(root: Path = REPO_ROOT) -> list[str]:
    """Return every build requirement of the workspace packages, then the third-party ones."""
    requirements: dict[str, None] = {}
    for pyproject in workspace_project_files(root):
        for requirement in project_requirements(pyproject):
            # Several packages share setuptools; one line per distinct
            # specifier is enough for the resolver to intersect them.
            requirements[requirement] = None
    for requirement in THIRD_PARTY_BUILD_REQUIREMENTS:
        requirements[requirement] = None
    return list(requirements)


def parse_compiled(output: str) -> list[Pin]:
    """Parse `uv pip compile --generate-hashes` output into pins."""
    pins: list[Pin] = []
    # Continuation lines end in a backslash; join them so each requirement is one record.
    for line in output.replace("\\\n", " ").splitlines():
        record = line.strip()
        if not record or record.startswith("#"):
            continue
        requirement, *hashes = (part.strip() for part in record.split("--hash="))
        if not hashes:
            raise BuildConstraintError(f"uv pip compile returned {requirement!r} without a hash")
        pins.append(Pin(requirement, tuple(sorted(hashes))))
    return sorted(pins, key=lambda pin: pin.requirement.lower())


def compile_pins(requirements: Sequence[str], *, uv: str = "uv") -> list[Pin]:
    """Resolve the build requirements to exact versions with every published hash."""
    with tempfile.TemporaryDirectory(prefix="citry-build-constraints-") as temporary:
        # --no-config keeps the current pins from steering the refresh, and
        # running outside the checkout keeps the workspace out of resolution.
        completed = subprocess.run(
            [
                uv,
                "pip",
                "compile",
                "-",
                "--no-config",
                "--generate-hashes",
                "--universal",
                "--python-version",
                OLDEST_PYTHON,
                "--no-header",
                "--no-annotate",
            ],
            input="".join(f"{requirement}\n" for requirement in requirements),
            cwd=temporary,
            capture_output=True,
            text=True,
            check=False,
        )
    if completed.returncode:
        raise BuildConstraintError(f"uv pip compile failed:\n{completed.stderr.strip()}")
    return parse_compiled(completed.stdout)


def rewrite_block(pyproject: Path, requirements: Sequence[str], *, uv: str = "uv") -> list[Pin]:
    """Rewrite the generated block in one pyproject with fresh pins for the requirements."""
    text = pyproject.read_text(encoding="utf-8")
    start, stop = marked_block(text)
    pins = compile_pins(requirements, uv=uv)
    # Entries take the END marker's indentation so the list stays aligned.
    end_line = text[stop : text.index(END_MARKER, stop)]
    pyproject.write_text(text[:start] + render_block(pins, indent=end_line) + text[stop:], encoding="utf-8")
    return pins


def update(*, root: Path = REPO_ROOT, uv: str = "uv") -> dict[Path, list[Pin]]:
    """Rewrite the generated block in the root pyproject and in each standalone project's pyproject."""
    pins = {root / "pyproject.toml": rewrite_block(root / "pyproject.toml", build_requirements(root), uv=uv)}
    # A standalone project is its own workspace root for uv, so its block
    # holds only what its own backend needs.
    for pyproject in standalone_project_files(root):
        pins[pyproject] = rewrite_block(pyproject, project_requirements(pyproject), uv=uv)
    return pins


def requirements_text(pins: Sequence[Pin]) -> str:
    """Render pins as a requirements file that `--build-constraints` accepts."""
    lines: list[str] = []
    for pin in pins:
        hashes = [f"    --hash={digest}" for digest in pin.hashes]
        lines.append(" \\\n".join([pin.requirement, *hashes]))
    return "".join(f"{line}\n" for line in lines)


def export(path: Path, *, pyproject: Path = ROOT_PYPROJECT) -> Path:
    """Write the root table's pins to `path` as a hashed requirements file."""
    pins = parse_pins(pyproject.read_text(encoding="utf-8"))
    # An empty file would let a --require-hashes build fail with a vague
    # message, so stop here with one that names the cause.
    if not pins:
        raise BuildConstraintError(f"{pyproject} has no build constraints to export")
    path.write_text(requirements_text(pins), encoding="utf-8")
    return path


def constraint_args(path: Path) -> list[str]:
    """Return the `uv build` arguments that apply exported pins and require their hashes."""
    # With --require-hashes, uv refuses a build dependency the file does not
    # pin with a hash, which covers transitive build dependencies too.
    return ["--build-constraints", str(path), "--require-hashes"]


@contextlib.contextmanager
def exported_constraint_args(*, pyproject: Path = ROOT_PYPROJECT) -> Iterator[list[str]]:
    """Export the pins to a temporary file and yield the `uv build` arguments that use it."""
    with tempfile.TemporaryDirectory(prefix="citry-build-constraints-") as temporary:
        yield constraint_args(export(Path(temporary) / "build-constraints.txt", pyproject=pyproject))


def main(argv: Sequence[str] | None = None) -> int:
    """Refresh or export the build-backend pins."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    subparsers = parser.add_subparsers(dest="command", required=True)
    update_parser = subparsers.add_parser("update", help="refresh the pins and hashes in the root pyproject.toml")
    update_parser.add_argument("--uv", default="uv", help="the uv executable to resolve with")
    export_parser = subparsers.add_parser("export", help="write the pins as a requirements file with hashes")
    export_parser.add_argument("path", type=Path, help="where to write the requirements file")
    args = parser.parse_args(argv)
    try:
        if args.command == "update":
            updated = update(uv=args.uv)
            locks = ["uv lock"]
            for pyproject, pins in updated.items():
                relative = pyproject.relative_to(REPO_ROOT)
                sys.stdout.write(f"Pinned {len(pins)} build dependencies in {relative}.\n")
                # `uv sync --frozen` reads the pins from the lockfile, so a standalone project's lock must record them.
                if pyproject != ROOT_PYPROJECT:
                    locks.append(f"uv lock --directory {relative.parent}")
            sys.stdout.write("Run " + ", then ".join(f"`{lock}`" for lock in locks) + " to record them.\n")
        else:
            export(args.path)
    except BuildConstraintError as error:
        parser.exit(1, f"build constraints: {error}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
